import { test, expect } from '@playwright/test';
import { readFileSync, mkdirSync } from 'node:fs';
const credentials = JSON.parse(readFileSync('D:/ManagementProduct-Credentials/admin-login.json', 'utf8'));
mkdirSync('docs/screenshots', { recursive: true });
test('admin login, product CRUD, image upload, mobile layout and logout', async ({ page }) => {
  const name = 'Sản phẩm demo ' + Date.now();
  await page.goto('/admin/products');
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('Email', { exact: true }).waitFor();
  await page.screenshot({ path: 'docs/screenshots/00-login-web.png', fullPage: true, animations: 'disabled' });
  await page.getByLabel('Email', { exact: true }).fill(credentials.adminEmail);
  await page.getByLabel('Mật khẩu', { exact: true }).fill(credentials.password);
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/products$/);
  await expect(page.getByTestId('product-row').first()).toBeVisible();
  await page.getByRole('button', { name: 'Cài đặt hệ thống', exact: true }).click();
  await page.getByLabel('Email hoặc UID tài khoản', { exact: true }).fill(credentials.adminEmail);
  await page.getByRole('button', { name: 'Thu hồi quyền admin', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận phân quyền', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Không thể tự thu hồi');
  await page.screenshot({ path: 'docs/screenshots/08-admin-roles.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Danh sách sản phẩm', exact: true }).click();
  await page.screenshot({ path: 'docs/screenshots/01-products-web.png', fullPage: true, animations: 'disabled' });
  try {
    await page.getByRole('button', { name: 'Thêm sản phẩm', exact: true }).click();
    await page.getByLabel('Tên sản phẩm', { exact: true }).fill(name);
    await page.getByLabel('Giá sản phẩm (VNĐ)', { exact: true }).fill('-1');
    await page.getByLabel('Số lượng', { exact: true }).fill('6');
    await page.getByLabel('URL hình ảnh', { exact: true }).fill('https://example.com/product.jpg');
    await page.getByRole('button', { name: 'Lưu sản phẩm', exact: true }).click();
    await expect(page.getByRole('alert')).toContainText('Giá phải là số');
    await page.getByLabel('Giá sản phẩm (VNĐ)', { exact: true }).fill('250000');
    const chooser = page.waitForEvent('filechooser');
    await page.getByRole('button', { name: 'Chọn ảnh sản phẩm', exact: true }).click();
    await (await chooser).setFiles('tests/fixtures/product.png');
    await expect(page.getByLabel('URL hình ảnh', { exact: true })).toHaveValue(/\/uploads\/.+\.jpg$/);
    await page.screenshot({ path: 'docs/screenshots/02-create-product-web.png', fullPage: true, animations: 'disabled' });
    await page.getByRole('button', { name: 'Lưu sản phẩm', exact: true }).click();
    await expect(page.getByText('Đã lưu sản phẩm.', { exact: true })).toBeVisible();
    const row = page.getByTestId('product-row').filter({ hasText: name });
    await expect(row).toBeVisible();
    await page.getByLabel('Tìm kiếm tên sản phẩm', { exact: true }).fill(name);
    await expect(page.getByTestId('product-row')).toHaveCount(1);
    await page.getByLabel('Giá từ', { exact: true }).fill('250000');
    await page.getByLabel('Giá đến', { exact: true }).fill('250000');
    await page.getByRole('button', { name: 'Áp dụng lọc giá', exact: true }).click();
    await expect(row).toBeVisible();
    await expect(page.getByTestId('active-price-range')).toContainText('250.000 đ');
    await page.screenshot({ path: 'docs/screenshots/09-price-filter.png', fullPage: true, animations: 'disabled' });
    await page.getByLabel('Giá từ', { exact: true }).fill('250001');
    await page.getByLabel('Giá đến', { exact: true }).fill('');
    await page.getByRole('button', { name: 'Áp dụng lọc giá', exact: true }).click();
    await expect(row).toHaveCount(0);
    await page.getByLabel('Giá từ', { exact: true }).fill('');
    await page.getByLabel('Giá đến', { exact: true }).fill('249999');
    await page.getByRole('button', { name: 'Áp dụng lọc giá', exact: true }).click();
    await expect(row).toHaveCount(0);
    await page.getByLabel('Giá từ', { exact: true }).fill('300000');
    await page.getByLabel('Giá đến', { exact: true }).fill('200000');
    await page.getByRole('button', { name: 'Áp dụng lọc giá', exact: true }).click();
    await expect(page.getByRole('alert').filter({ hasText: 'Giá từ phải nhỏ hơn' })).toBeVisible();
    await page.getByRole('button', { name: 'Xóa bộ lọc', exact: true }).click();
    await expect(row).toBeVisible();
    await page.getByRole('button', { name: 'Sắp xếp: Mặc định', exact: true }).click();
    await page.getByRole('button', { name: 'Giá giảm dần', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Sắp xếp: Giá giảm dần', exact: true })).toBeVisible();
    await page.reload();
    await expect(row).toBeVisible();
    await page.getByRole('button', { name: `Sửa ${name}`, exact: true }).click();
    await page.getByLabel('Giá sản phẩm (VNĐ)', { exact: true }).fill('290000');
    await page.getByLabel('Số lượng', { exact: true }).fill('9');
    await page.screenshot({ path: 'docs/screenshots/03-edit-product-web.png', fullPage: true, animations: 'disabled' });
    await page.getByRole('button', { name: 'Lưu sản phẩm', exact: true }).click();
    await expect(page.getByText('Đã lưu sản phẩm.', { exact: true })).toBeVisible();
    await expect(row.getByLabel('Số lượng: 9', { exact: true })).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: 'docs/screenshots/04-products-mobile-web.png', fullPage: true, animations: 'disabled' });
    await page.getByRole('button', { name: `Sửa ${name}`, exact: true }).click();
    const mobileChooser = page.waitForEvent('filechooser');
    await page.getByRole('button', { name: 'Chọn ảnh sản phẩm', exact: true }).click();
    await (await mobileChooser).setFiles('tests/fixtures/product.png');
    await expect(page.getByRole('button', { name: 'Chọn ảnh sản phẩm', exact: true })).toBeEnabled();
    await page.screenshot({ path: 'docs/screenshots/05-image-mobile-web.png', fullPage: true, animations: 'disabled' });
    await page.getByRole('button', { name: 'Lưu sản phẩm', exact: true }).click();
    await expect(page.getByText('Đã lưu sản phẩm.', { exact: true })).toBeVisible();
    await expect(row).toBeVisible();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: `Xóa ${name}`, exact: true }).click();
    await page.screenshot({ path: 'docs/screenshots/06-delete-product.png', fullPage: true, animations: 'disabled' });
    await page.getByRole('button', { name: 'Hủy xóa', exact: true }).click();
    await expect(row).toBeVisible();
    await page.getByRole('button', { name: `Xóa ${name}`, exact: true }).click();
    await page.getByRole('button', { name: 'Xác nhận xóa', exact: true }).click();
    await expect(row).toHaveCount(0);
    await expect(page.getByText('Đã xóa sản phẩm.', { exact: true })).toBeVisible();
  } finally {
    const row = page.getByTestId('product-row').filter({ hasText: name });
    if (await row.count()) {
      await page.getByRole('button', { name: `Xóa ${name}`, exact: true }).click();
      await page.getByRole('button', { name: 'Xác nhận xóa', exact: true }).click();
      await expect(row).toHaveCount(0);
    }
  }
  await page.getByRole('button', { name: 'Đăng xuất', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.goto('/admin/products');
  await expect(page).toHaveURL(/\/login$/);
});
